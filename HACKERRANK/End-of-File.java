import java.io.*;
import java.util.*;
import java.text.*;
import java.math.*;
import java.util.regex.*;

public class Solution {

    public static void main(String[] args) {
       Scanner s = new Scanner(System.in);
       int n = 1;
        while(s.hasNextLine()){
            String ss = s.nextLine();
            System.out.println(n+ " "+ ss);
            n++;
        }
      
    }
}
